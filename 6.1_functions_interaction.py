# 1. In:
#    A list of daily sales amounts in euros (sales) and a daily target threshold (target).
# 2. Process, function by function:
#    - Step 1: filter_above_target(sales, target) keeps only the sales values strictly above the target.
#    - Step 2: sum_sales(sales) adds up all the numbers in a given list of sales.
#    - Step 3: compute_percentage(part, total) calculates the percentage that a partial sum represents out of a total sum.
#    - Step 4: calculate_high_day_revenue_share(sales, target) calls these three functions in order to get the final share.
# 3. Out:
#    A float representing the percentage of total revenue generated by days that beat the daily target.
# 4. The question my fourth function answers:
#    Question: "What percentage of our total revenue comes from high-performing days that beat our daily target?"
#    Why splitting helps: Each small function does a single, isolated job, so we can test each step
#    separately with simple inputs and immediately spot where an error occurs if the final percentage is wrong.


# Your code below

# Function 1: Returns a list containing only the sales values greater than the target.
def filter_above_target(sales, target):
    return [amount for amount in sales if amount > target]


# Function 2: Calculates the sum of all numbers in a list of sales.
def sum_sales(sales):
    return sum(sales)


# Function 3: Computes what percentage a partial value represents out of a total value.
def compute_percentage(part, total):
    if total == 0:
        return 0.0
    return (part / total) * 100


# Function 4: Combines the three functions to find the revenue share of above-target days.
def calculate_high_day_revenue_share(sales, target):
    high_days = filter_above_target(sales, target)
    high_days_revenue = sum_sales(high_days)
    total_revenue = sum_sales(sales)
    return compute_percentage(high_days_revenue, total_revenue)


# --- Three test cases for the individual functions ---

# Test case 1 (filter_above_target):
# Input: sales = [80.0, 150.0, 95.0, 200.0, 75.0], target = 100.0
# Expected output: [150.0, 200.0]
print("Test 1 - filter_above_target:", filter_above_target([80.0, 150.0, 95.0, 200.0, 75.0], 100.0))

# Test case 2 (sum_sales):
# Input: sales = [150.0, 200.0]
# Expected output: 350.0
print("Test 2 - sum_sales:", sum_sales([150.0, 200.0]))

# Test case 3 (compute_percentage):
# Input: part = 350.0, total = 600.0
# Expected output: 58.33 (58.333333333333336)
print(f"Test 3 - compute_percentage: {compute_percentage(350.0, 600.0):.2f}%")


# --- Final call using the fourth combined function ---
daily_sales = [80.0, 150.0, 95.0, 200.0, 75.0]
daily_target = 100.0

revenue_share = calculate_high_day_revenue_share(daily_sales, daily_target)
print(f"High-day revenue share (days > {daily_target:.0f} EUR): {revenue_share:.2f}%")
